def normalize_period(value: Any, *, default: str | None = None) -> str:
    """把页面/接口里的各种写法归一到周期的标准编号。"""
    text = str(value or "").strip()
    if not text:
        return default or DEFAULT_PERIOD
    if text in PERIOD_BASE:
        return text
    lowered = text.casefold()
    if lowered in PERIOD_ALIASES:
        return PERIOD_ALIASES[lowered]
    digits = "".join(ch for ch in text if ch.isdigit())
    if digits:
        week = digits[-2:].lstrip("0") or "0"
        candidate = f"2026-W{int(week):02d}"
        if candidate in PERIOD_BASE:
            return candidate
    return default or DEFAULT_PERIOD
